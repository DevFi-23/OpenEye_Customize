"""Build the bug #14 lock-step check: the old (HEAD) and new psum_pipeline side by side.

Usage: make_lockstep.py [old revision, default 35f747f]. Writes psum_pipeline_orig.v, psum_pipeline_fix.v and psum_pipeline_lockstep.v (module psum_pipeline:
same parameters and ports, outputs driven by the new module, every output compared with the old
one at each falling clock edge; the first mismatch stops the simulation with $fatal)."""
import os
import re
import subprocess
import sys

REPO = "/home/truongphi/OpenEye_orig"
HERE = os.path.dirname(os.path.abspath(__file__))

OLD_REV = sys.argv[1] if len(sys.argv) > 1 else "35f747f"   # last commit before the bug #14 fix
old = subprocess.run(["git", "show", f"{OLD_REV}:hdl/psum_pipeline.v"], cwd=REPO, capture_output=True, text=True,
                     check=True).stdout
new = open(os.path.join(REPO, "hdl", "psum_pipeline.v")).read()
for name, src in (("orig", old), ("fix", new)):
    out = re.sub(r"^module psum_pipeline\b", f"module psum_pipeline_{name}", src, count=1, flags=re.M)
    assert out != src
    open(os.path.join(HERE, f"psum_pipeline_{name}.v"), "w").write(out)

header = new[new.index("module psum_pipeline"):new.index(");", new.index(") (")) + 2]
params = re.findall(r"parameter\s+(\w+)\s*=\s*([^,\n]+)", header[:header.index(") (")])
ports = []
for m in re.finditer(r"^\s*(input|output)\s+(?:wire|reg)?\s*(\[[^\]]+\])?\s*(\w+)\s*,?\s*$", header, re.M):
    ports.append((m.group(1), m.group(2) or "", m.group(3)))
assert len(ports) == 77, len(ports)   # every input/output line of the module header

lines = ["`timescale 1ns / 1ps", "// Generated by make_lockstep.py (bug #14 verification, not project RTL).",
         "module psum_pipeline #("]
lines += [f"    parameter {n} = {v.strip()}{',' if i < len(params) - 1 else ''}" for i, (n, v) in enumerate(params)]
lines.append(") (")
lines += [f"    {d} wire {w} {n}{',' if i < len(ports) - 1 else ''}" for i, (d, w, n) in enumerate(ports)]
lines.append(");")
outs = [(w, n) for d, w, n in ports if d == "output"]
for w, n in outs:
    lines.append(f"  wire {w} {n}__orig;")
plist = ", ".join(f".{n}({n})" for n, _ in params)
for tag in ("fix", "orig"):
    conns = ", ".join(f".{n}({n}{'__orig' if (tag == 'orig' and d == 'output') else ''})" for d, w, n in ports)
    lines.append(f"  psum_pipeline_{tag} #({plist}) u_{tag} ({conns});")
lines += ["  integer lockstep_cycles = 0;", "  integer lockstep_mismatches = 0;", "  always @(negedge clk_i) if (rst_n) begin",
          "    lockstep_cycles = lockstep_cycles + 1;"]
for w, n in outs:
    lines.append(f"    if ({n} !== {n}__orig) begin $display(\"LOCKSTEP MISMATCH %0t ns: {n} fix=%h orig=%h\", $time, {n}, {n}__orig); "
                 f"lockstep_mismatches = lockstep_mismatches + 1; $fatal(1, \"LOCKSTEP MISMATCH\"); end")
lines += ["  end", "  final $display(\"LOCKSTEP %s: %0d cycles, %0d outputs compared every cycle, %0d mismatches\", "
          f"lockstep_mismatches ? \"FAIL\" : \"OK\", lockstep_cycles, {len(outs)}, lockstep_mismatches);", "endmodule", ""]
open(os.path.join(HERE, "psum_pipeline_lockstep.v"), "w").write("\n".join(lines))
print(f"{len(params)} parameters, {len(ports)} ports, {len(outs)} outputs compared")
